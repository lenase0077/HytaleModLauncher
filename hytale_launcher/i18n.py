def tr(key: str, *args) -> str:
    """Translates a given key to the current language."""
    lang = config_store.load_language()
    dict_lang = _LANGUAGES.get(lang) or _LANGUAGES["es"]
    text = dict_lang.get(key, key)
    if args:
        try:
            return text.format(*args)
        except IndexError:
            return text
    return text
